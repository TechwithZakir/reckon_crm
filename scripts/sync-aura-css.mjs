// Copies the Aura tokens (section 2), the tools and Ask panel (section 7) and the Ask-panel text rules from the
// Desk stylesheet into the CRM, so the CRM's Ask Aura AI looks exactly like the Desk's.
// Usage: node scripts/sync-aura-css.mjs [path/to/aura_desk.css]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const source = process.argv[2] || path.resolve(here, '../../reckon_aura_theme/reckon_aura_theme/public/css/aura_desk.css')
const target = path.resolve(here, '../frontend/src/extensions/theme/aura-desk-ui.css')
const css = fs.readFileSync(source, 'utf8')

const between = (from, to) => {
  const a = css.search(from)
  const b = css.search(to)
  if (a < 0 || b < 0 || b <= a) throw new Error(`Section not found: ${from} .. ${to}`)
  return css.slice(a, b).trimEnd() + '\n'
}
const tokens = between(/\/\* -+ 2\. tokens \*\//, /\/\* -+ 3\. Frappe token map/)
const ui = between(/\/\* -+ 7\. Aura UI \*\//, /\/\* -+ 8\. responsive \*\//)
const tailAt = css.indexOf('/* The Ask panel is read and copied from')
const tail = tailAt >= 0 ? css.slice(tailAt).trimEnd() + '\n' : ''

const header = `/*
 * Aura Desk UI tokens and toolbar/Ask-panel styles, copied verbatim from
 * reckon_aura_theme/public/css/aura_desk.css (sections 2 and 7, and the Ask-panel text rules).
 * Generated by scripts/sync-aura-css.mjs: re-run it when that file changes so the CRM matches the Desk exactly.
 */
`
fs.writeFileSync(target, header + tokens + '\n' + ui + '\n' + tail)
console.log(`Wrote ${path.relative(process.cwd(), target)} from ${source}`)
